/**
 * Demonstrates the use of Unary Plus (+) operator in Java.
 *
 * @author Coding Wars
 */
public class UnaryPlus {
    public static void main(String[] args) {

        // Store a number
        int number = 10;

        // Apply the unary plus operator
        int result = +number;

        // Display the result
        System.out.println("Unary Plus: " + result);
    }
}