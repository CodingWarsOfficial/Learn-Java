/**
 * Demonstrates the use of Increment (++) unary operator in Java.
 *
 * @author Coding Wars
 */
public class UnaryIncrement {
    public static void main(String[] args) {

        // Store an initial value
        int number = 10;

        // Increase the value by 1
        number++;

        // Display the updated value
        System.out.println("Increment: " + number);
    }
}