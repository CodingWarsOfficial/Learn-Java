/**
 * Demonstrates the use of Division (/) arithmetic operator in Java.
 *
 * @author Coding Wars
 */
public class ArithmeticDivision {
    public static void main(String[] args) {

        // Store two numbers
        int a = 20;
        int b = 10;

        // Divide a by b using the division operator
        int result = a / b;

        // Display the result
        System.out.println("Division: " + result);
    }
}