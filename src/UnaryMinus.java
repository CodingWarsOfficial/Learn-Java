/**
 * Demonstrates the use of Unary Minus (-) operator in Java.
 *
 * @author Coding Wars
 */
public class UnaryMinus {
    public static void main(String[] args) {

        // Store a positive number
        int number = 10;

        // Apply the unary minus operator
        int result = -number;

        // Display the result
        System.out.println("Unary Minus: " + result);
    }
}