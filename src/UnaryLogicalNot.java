/**
 * Demonstrates the use of Logical NOT (!) unary operator in Java.
 *
 * @author Coding Wars
 */
public class UnaryLogicalNot {
    public static void main(String[] args) {

        // Store a Boolean value
        boolean isJavaEasy = true;

        // Reverse the Boolean value using the logical NOT operator
        boolean result = !isJavaEasy;

        // Display the result
        System.out.println("Logical NOT: " + result);
    }
}