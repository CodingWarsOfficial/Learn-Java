/**
 * Demonstrates the use of Multiplication (*) arithmetic operator in Java.
 *
 * @author Coding Wars
 */
public class ArithmeticMultiplication {
    public static void main(String[] args) {

        // Store two numbers
        int a = 20;
        int b = 10;

        // Multiply both numbers using the multiplication operator
        int result = a * b;

        // Display the result
        System.out.println("Multiplication: " + result);
    }
}