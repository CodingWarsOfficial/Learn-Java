/**
 * Demonstrates the use of Decrement (--) unary operator in Java.
 *
 * @author Coding Wars
 */
public class UnaryDecrement {
    public static void main(String[] args) {

        // Store an initial value
        int number = 10;

        // Decrease the value by 1
        number--;

        // Display the updated value
        System.out.println("Decrement: " + number);
    }
}