/**
 * Demonstrates the use of Less Than (<) relational operator in Java.
 *
 * @author Coding Wars
 */
public class RelationalLessThan {
    public static void main(String[] args) {

        // Store two numbers
        int a = 10;
        int b = 20;

        // Check whether a is less than b
        if (a < b) {
            System.out.println(a + " is less than " + b);
        } else {
            System.out.println(a + " is not less than " + b);
        }
    }
}