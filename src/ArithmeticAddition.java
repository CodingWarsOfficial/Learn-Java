/**
 * Demonstrates the use of Addition (+) arithmetic operator in Java.
 *
 * @author Coding Wars
 */
public class ArithmeticAddition {
    public static void main(String[] args) {

        // Store two numbers
        int a = 20;
        int b = 10;

        // Add both numbers using the addition operator
        int result = a + b;

        // Display the result
        System.out.println("Addition: " + result);
    }
}