/**
 * Demonstrates the use of Less Than or Equal To (<=) relational operator.
 *
 * @author Coding Wars
 */
public class RelationalLessThanOrEqual {
    public static void main(String[] args) {

        // Store the speed of a vehicle
        int speed = 60;

        // Check whether speed is 60 or less
        if (speed <= 60) {
            System.out.println("Speed is within the limit.");
        } else {
            System.out.println("Speed is above the limit.");
        }
    }
}