/**
 * Demonstrates the use of Not Equal To (!=) relational operator in Java.
 *
 * @author Coding Wars
 */
public class RelationalNotEqualTo {
    public static void main(String[] args) {

        // Store two numbers
        int a = 10;
        int b = 20;

        // Check whether both numbers are different
        if (a != b) {
            System.out.println("Both numbers are different.");
        } else {
            System.out.println("Both numbers are equal.");
        }
    }
}