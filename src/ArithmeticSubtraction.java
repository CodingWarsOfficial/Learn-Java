/**
 * Demonstrates the use of Subtraction (-) arithmetic operator in Java.
 *
 * @author Coding Wars
 */
public class ArithmeticSubtraction {
    public static void main(String[] args) {

        // Store two numbers
        int a = 20;
        int b = 10;

        // Subtract b from a using the subtraction operator
        int result = a - b;

        // Display the result
        System.out.println("Subtraction: " + result);
    }
}