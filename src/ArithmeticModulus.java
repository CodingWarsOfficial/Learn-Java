/**
 * Demonstrates the use of Modulus (%) arithmetic operator in Java.
 *
 * @author Coding Wars
 */
public class ArithmeticModulus {
    public static void main(String[] args) {

        // Store two numbers
        int a = 20;
        int b = 6;

        // Find the remainder using the modulus operator
        int result = a % b;

        // Display the remainder
        System.out.println("Modulus: " + result);
    }
}