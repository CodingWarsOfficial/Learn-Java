/**
 * Demonstrates the use of Greater Than (>) relational operator in Java.
 *
 * @author Coding Wars
 */
public class RelationalGreaterThan {
    public static void main(String[] args) {

        // Store two numbers
        int a = 20;
        int b = 10;

        // Check whether a is greater than b
        if (a > b) {
            System.out.println(a + " is greater than " + b);
        } else {
            System.out.println(a + " is not greater than " + b);
        }
    }
}