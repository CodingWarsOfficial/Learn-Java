/**
 * Demonstrates the use of Greater Than or Equal To (>=) relational operator.
 *
 * @author Coding Wars
 */
public class RelationalGreaterThanOrEqual {
    public static void main(String[] args) {

        // Store the person's age
        int age = 18;

        // Check whether age is 18 or greater
        if (age >= 18) {
            System.out.println("You are eligible.");
        } else {
            System.out.println("You are not eligible.");
        }
    }
}